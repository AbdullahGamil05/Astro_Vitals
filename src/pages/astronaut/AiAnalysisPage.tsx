import { Loader2, Sparkles } from "lucide-react";
import { useCallback, useEffect, useRef, useState } from "react";
import { AnalysisView } from "@/components/AnalysisView";
import { Card } from "@/components/ui/primitives";
import { useAuth } from "@/lib/auth";
import { useLive } from "@/lib/liveData";
import { requestAnalysis, isRemoteConfigured, type AnalysisResult } from "@/services/ai/client";
import type { AnalysisRequest } from "@/services/ai/schema";
import { useAnalysisRequestBuilder } from "@/services/ai/useAnalysisRequest";

type RunState =
  | { status: "idle" }
  | { status: "loading" }
  | { status: "done"; result: AnalysisResult; request: AnalysisRequest }
  | { status: "error"; message: string };

const sourceNote = {
  "demo-engine": "Generated by the built-in deterministic demo engine (rule-based, runs in your browser).",
  "remote-model": "Generated by the configured remote analysis model.",
  fallback: "The remote model was unavailable, so the built-in demo engine answered instead.",
} as const;

export function AiAnalysisPage() {
  const { user } = useAuth();
  const { completeTask } = useLive();
  const build = useAnalysisRequestBuilder(user?.astronautId);
  const [run, setRun] = useState<RunState>({ status: "idle" });
  const controller = useRef<AbortController | null>(null);
  const analyseRef = useRef<() => Promise<void>>(async () => {});

  const analyse = useCallback(async () => {
    const request = build();
    if (!request) return;
    controller.current?.abort();
    const ctl = new AbortController();
    controller.current = ctl;
    setRun({ status: "loading" });
    try {
      const result = await requestAnalysis(request, ctl.signal);
      if (!ctl.signal.aborted) {
        setRun({ status: "done", result, request });
        if (user?.astronautId) completeTask(user.astronautId, "aiReview");
      }
    } catch (e) {
      if (!ctl.signal.aborted) setRun({ status: "error", message: e instanceof Error ? e.message : "Analysis failed." });
    }
  }, [build, completeTask, user?.astronautId]);

  analyseRef.current = analyse;

  useEffect(() => {
    void analyseRef.current();
    return () => controller.current?.abort();
  }, []);

  return (
    <div className="mx-auto max-w-5xl space-y-4">
      <Card>
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div>
            <h2 className="flex items-center gap-2 text-base font-semibold text-ink">
              <Sparkles className="size-4 text-orbit-cyan" aria-hidden="true" />
              AI health analysis
            </h2>
            <p className="mt-1 max-w-xl text-sm text-orbit-muted">
              Reviews your last 24 hours of readings, alerts and latest check-in against your personal baseline. It supports decisions and never replaces medical advice.
            </p>
          </div>
          <button
            type="button"
            onClick={() => void analyse()}
            disabled={run.status === "loading"}
            className="inline-flex h-10 items-center gap-2 rounded-lg bg-orbit-cyan px-4 text-sm font-semibold text-orbit-bg transition-colors hover:bg-orbit-cyan/90 disabled:opacity-60"
          >
            {run.status === "loading" ? <Loader2 className="size-4 animate-spin" aria-hidden="true" /> : null}
            {run.status === "loading" ? "Analysing…" : "Run analysis again"}
          </button>
        </div>
        <p className="mt-3 text-xs text-orbit-dim">
          {isRemoteConfigured ? "A remote model endpoint is configured." : "No remote model is configured; the demo engine is used."}
        </p>
      </Card>

      <div aria-live="polite">
        {run.status === "loading" || run.status === "idle" ? (
          <Card>
            <div className="flex items-center gap-3 text-sm text-orbit-muted">
              <Loader2 className="size-4 animate-spin text-orbit-cyan" aria-hidden="true" />
              Analysing your recent data…
            </div>
          </Card>
        ) : null}
        {run.status === "error" ? (
          <Card>
            <p className="text-sm text-orbit-crit">{run.message}</p>
          </Card>
        ) : null}
        {run.status === "done" ? (
          <AnalysisView
            analysis={run.result.analysis}
            banner={
              <p className="rounded-lg border border-orbit-line bg-black/20 px-3 py-2 text-xs text-orbit-muted">
                {sourceNote[run.result.source]} Completed in {Math.round(run.result.latencyMs)} ms.
                {run.result.error ? ` Reason: ${run.result.error}` : ""}
              </p>
            }
          />
        ) : null}
      </div>

      {run.status === "done" ? (
        <details className="rounded-lg border border-orbit-line bg-black/20 p-4">
          <summary className="cursor-pointer text-sm font-medium text-ink">Data sent to the analysis engine</summary>
          <pre className="mt-3 max-h-80 overflow-auto rounded-lg bg-black/40 p-3 font-mono text-[11px] leading-relaxed text-orbit-muted">
            {JSON.stringify(run.request, null, 2)}
          </pre>
        </details>
      ) : null}
    </div>
  );
}
